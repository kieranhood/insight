def vendor_for(mac: str | None) -> str | None:
    normalised = normalise_mac(mac)
    if not normalised:
        return None
    prefix = normalised[:8]
    for vendor, prefixes in VENDOR_OUIS.items():
        if prefix in prefixes:
            return vendor
    return None


def is_locally_administered(mac: str | None) -> bool:
    """Randomised (private) MAC addresses, as phones use, have this bit set."""
    normalised = normalise_mac(mac)
    return bool(normalised) and bool(int(normalised[:2], 16) & 0x02)  # type: ignore[index]
